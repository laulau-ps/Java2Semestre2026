package aulas;

public class ExOperadoresAritmeticos {
public static void main(String[] args){
    int x = 10;
    int y = 3;

    System.out.println(x + y); // soma
    System.out.println(x - y); // subtração
    System.out.println(x * y); // multiplicação
    System.out.println(x / y); // divisão
    System.out.println(x % y); // modulo (resto da divisão)

    int z = 5;
    ++z;
    System.out.println(z); // incremento
    z--;
    System.out.println(z); // decremento


}
}
